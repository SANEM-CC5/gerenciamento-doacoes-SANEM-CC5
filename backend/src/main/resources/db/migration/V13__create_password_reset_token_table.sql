-- =====================================================================
-- V13: Tabela de tokens para recuperação de senha antes do login
-- (PostgreSQL)
-- =====================================================================

CREATE TABLE IF NOT EXISTS password_reset_token (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    used_at TIMESTAMP(6) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_password_reset_token_user
        FOREIGN KEY (user_id)
        REFERENCES app_user(user_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_password_reset_token_hash
    ON password_reset_token (token_hash);

CREATE INDEX IF NOT EXISTS idx_password_reset_token_user_expires
    ON password_reset_token (user_id, expires_at);

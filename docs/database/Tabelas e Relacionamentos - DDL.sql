CREATE TABLE profile (
    profile_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    deleted_at TIMESTAMP(6) NULL,
    CONSTRAINT uq_profile_name UNIQUE (name)
);

CREATE TABLE app_user (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    login VARCHAR(60) NOT NULL,
    email VARCHAR(160) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    profile_id INTEGER NOT NULL,
    deleted_at TIMESTAMP(6) NULL,
    CONSTRAINT fk_app_user_profile FOREIGN KEY (profile_id) REFERENCES profile(profile_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_user_login UNIQUE (login),
    CONSTRAINT uq_user_email UNIQUE (email)
);

-- ==========================================
-- 2. BENEFICIÁRIOS
-- Status INACTIVE permite inativar/bloquear beneficiários aprovados sem
-- removê-los. O soft delete usa deleted_at.
-- ==========================================
CREATE TABLE beneficiary (
    beneficiary_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(160) NOT NULL,
    cpf VARCHAR(14) NOT NULL,
    phone VARCHAR(120),
    socioeconomic_data TEXT,
    beneficiary_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    approver_user_id INTEGER,
    withdrawal_limit INTEGER DEFAULT NULL,
    deleted_at TIMESTAMP(6) NULL,
    CONSTRAINT fk_beneficiary_approver FOREIGN KEY (approver_user_id) REFERENCES app_user(user_id)
        ON UPDATE RESTRICT ON DELETE SET NULL,
    CONSTRAINT uq_beneficiary_cpf UNIQUE (cpf),
    CONSTRAINT chk_beneficiary_status CHECK (beneficiary_status IN ('PENDING', 'APPROVED', 'REJECTED', 'INACTIVE'))
);

CREATE TABLE card (
